"""
report_md.py — renders a scan's findings as a standalone Markdown writeup.

CyberSci (and most jeopardy CTFs) are played in teams, usually over
Discord/Slack, usually under a ticking clock. The person who runs flagmap
is rarely the only one who needs the results — a teammate picks up "try
the IDOR on /orders/<id>" and runs with it while the first person keeps
digging. Reading that off a terminal screen means re-describing it by hand
in chat; this renders the exact same findings/chains print_report() already
computed as one shareable `.md` file instead, so "paste it in Discord" or
"drop it in the team's shared doc" is a straight file hand-off, not a
retyping exercise.

Deliberately NOT a separate code path from the terminal report: this module
takes the exact same `findings`/`chains` objects cli.py's print_report()
already builds, and formats them as Markdown instead of ANSI-colored text —
same grouping, same section order (Loot/Recon, Vulnerable Dependencies,
Code Vulnerabilities, Misconfigurations, Attack Chains, Start Here), same
content. If print_report()'s sectioning or "Start Here" ranking ever
changes, this should change with it — see cli.py's `_print_start_here`'s
`rank_key` for the canonical ordering this mirrors.
"""

from collections import defaultdict
from datetime import datetime, timezone
from typing import List

from . import __version__

# Kept as its own copy, not imported from cli.py: cli.py will need to
# import render_markdown() from this module to wire up a CLI flag for it,
# and importing SEVERITY_ORDER back the other way would make that a
# circular import. Three stable entries, extremely unlikely to drift —
# if cli.py's copy ever changes, change this one too.
SEVERITY_ORDER = {"high": 0, "medium": 1, "low": 2}


def _kind(f) -> str:
    return getattr(f, "kind", "vuln")


def _loc(f) -> str:
    # line_no 0 means "this finding is about the file/directory itself,
    # not one line in it" — same convention cli.py's _print_group/
    # _print_start_here use for loot.py's presence-only findings.
    return f.file if f.line_no == 0 else f"{f.file}:{f.line_no}"


def _section(title: str, subtitle: str, findings: List, action_label: str) -> List[str]:
    lines = [f"## {title}", "", f"*{subtitle}*", ""]
    grouped = defaultdict(list)
    for f in findings:
        grouped[f.vuln_name].append(f)

    def group_rank(name):
        worst = min(SEVERITY_ORDER.get(f.severity, 3) for f in grouped[name])
        return (worst, name)

    for vuln_name in sorted(grouped, key=group_rank):
        items = sorted(grouped[vuln_name], key=lambda f: SEVERITY_ORDER.get(f.severity, 3))
        plural = "es" if len(items) != 1 else ""
        lines.append(f"### {vuln_name} ({len(items)} match{plural})")
        lines.append("")
        for f in items:
            lines.append(f"- **[{f.severity.upper()}/{f.confidence}]** `{_loc(f)}`")
            lines.append(f"  ```")
            lines.append(f"  {f.line_text}")
            lines.append(f"  ```")
            lines.append(f"  - **why:** {f.why}")
            lines.append(f"  - **{action_label}:** {f.payload}")
        lines.append("")
    return lines


def render_markdown(findings: List, chains: List, scanned_path: str) -> str:
    out: List[str] = []
    out.append(f"# flagmap report — `{scanned_path}`")
    out.append("")
    out.append(f"*Generated by flagmap {__version__} on "
                f"{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}*")
    out.append("")

    if not findings:
        out.append("No known vulnerable patterns or misconfigurations found.")
        out.append("")
        out.append("*(Doesn't mean it's safe — stay sharp.)*")
        out.append("")
        return "\n".join(out)

    loot_findings = [f for f in findings if _kind(f) == "loot"]
    dep_findings = [f for f in findings if _kind(f) == "dep"]
    code_findings = [f for f in findings if _kind(f) == "vuln"]
    config_findings = [f for f in findings if _kind(f) == "misconfig"]

    n_classes = len({f.vuln_name for f in findings})
    sev_counts = defaultdict(int)
    for f in findings:
        sev_counts[f.severity] += 1
    sev_summary = " · ".join(
        f"{sev_counts[s]} {s}" for s in ("high", "medium", "low") if sev_counts[s]
    )
    chain_note = f" · {len(chains)} attack chain{'s' if len(chains) != 1 else ''} detected" if chains else ""
    out.append(f"**{len(findings)} finding(s)** across **{n_classes} class(es)** "
                f"[{sev_summary}]{chain_note}")
    out.append("")

    chained_ids = set()
    for ch in chains:
        for f in ch.findings:
            chained_ids.add(id(f))

    if findings:
        out.append("## Start Here")
        out.append("")
        out.append("*Highest-value findings first (loot, then known-CVE deps, then severity + "
                    "confidence + attack-chain membership).*")
        out.append("")

        def rank_key(f):
            kind = _kind(f)
            tier = 0 if kind == "loot" else 1 if kind == "dep" else 2
            sev = SEVERITY_ORDER.get(f.severity, 3)
            conf = 0 if f.confidence == "likely" else 1
            chained = 0 if id(f) in chained_ids else 1
            return (tier, chained, sev, conf)

        top = sorted(findings, key=rank_key)[:5]
        for i, f in enumerate(top, start=1):
            tag = " **(part of an attack chain)**" if id(f) in chained_ids else ""
            out.append(f"{i}. **[{f.severity.upper()}/{f.confidence}]** {f.vuln_name} — "
                        f"`{_loc(f)}`{tag}")
        out.append("")

    if loot_findings:
        out.extend(_section(
            "Loot / Recon", "Needs zero exploitation — just open the file. Check this before "
                             "anything else below.", loot_findings, "do"))

    if dep_findings:
        out.extend(_section(
            "Vulnerable Dependencies", "Exact pinned version matched a known CVE — see \"fix\" "
                                       "for the patched version.", dep_findings, "fix"))

    if code_findings:
        out.extend(_section("Code Vulnerabilities", "Patterns matched in source.",
                             code_findings, "try"))

    if config_findings:
        out.extend(_section("Misconfigurations", "Infra/config issues, not source-code bugs.",
                             config_findings, "fix"))

    if chains:
        out.append("## Attack Chains")
        out.append("")
        out.append("*Correlated from the findings above — a strong hint of what to try first, "
                    "not a guarantee.*")
        out.append("")
        for ch in sorted(chains, key=lambda x: SEVERITY_ORDER.get(x.severity, 3)):
            out.append(f"### [{ch.severity.upper()}] {ch.name}")
            out.append("")
            out.append(f"- **path:** {ch.steps}")
            out.append(f"- **why:** {ch.why}")
            based_on = ", ".join(f"`{f.file}:{f.line_no}` ({f.vuln_name})" for f in ch.findings)
            out.append(f"- **based on:** {based_on}")
            out.append("")

    return "\n".join(out)
